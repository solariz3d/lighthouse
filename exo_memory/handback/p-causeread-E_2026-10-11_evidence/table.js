// table.js (pane E, D303 part 3): the shares by B's §4, the joint table by §5 and the §6 conditions, from classification.json.
//   node table.js            -> writes out/table.md and out/table.tsv, prints table.md
// Every number in the hand-back is printed by this script; nothing is hand-counted.
'use strict';
const fs = require('fs'), path = require('path');
const C = JSON.parse(fs.readFileSync(path.join(__dirname, 'classification.json'), 'utf8'));
const { X, ND, UC, NA } = require('./dump.js');
const fail = (m) => { console.error('FAIL: ' + m); process.exit(1); };
const pct = (a, b) => (b ? (100 * a / b).toFixed(1) + '%' : 'n/a');
const count = (rows, k) => rows.filter((r) => r.class === k).length;

// populations: exactly B's §1 lists, each unit once
const q3ids = C.q3.map((r) => r.id), q2ids = C.q2.map((r) => r.id);
const want3 = [...X, ...ND, ...UC], want2 = NA;
if (new Set(q3ids).size !== q3ids.length || q3ids.length !== 47 || want3.some((i) => !q3ids.includes(i))) fail('Q3 is not the 47 of X+ND+UC, once each');
if (new Set(q2ids).size !== q2ids.length || q2ids.length !== 41 || want2.some((i) => !q2ids.includes(i))) fail('Q2 is not the 41 NA, once each');
const Q3K = ['CN', 'CR', 'CU', 'NC', 'QX'], Q2K = ['RF', 'RX', 'RN', 'QN'];
for (const r of C.q3) if (!Q3K.includes(r.class)) fail(`${r.id}: ${r.class}`);
for (const r of C.q2) if (!Q2K.includes(r.class)) fail(`${r.id}: ${r.class}`);

const L = [];
const q3 = Object.fromEntries(Q3K.map((k) => [k, count(C.q3, k)]));
const Dq = q3.CN + q3.CR + q3.CU + q3.NC;
L.push('# D303 part 3: the blind read (pane E). Generated by table.js from classification.json.', '');
L.push('## Q3, unchecked claims (47 units: D301 X 29 + ND 11 + UC 7)', '');
L.push('| class | n |', '|---|---:|', ...Q3K.map((k) => `| ${k} | ${q3[k]} |`), `| **total** | ${47} |`, '');
L.push(`Dq = CN + CR + CU + NC = ${Dq}. **Unchecked share: low ${pct(q3.CN, Dq)} (CN/Dq), high ${pct(q3.CN + q3.CU, Dq)} ((CN+CU)/Dq).** QX ${q3.QX} of 47 (${pct(q3.QX, 47)}).`);
const lo3 = q3.CN / Dq, hi3 = (q3.CN + q3.CU) / Dq;
const band = (lo, hi) => (hi < 0.2 ? 'high < 20%' : lo >= 0.4 ? 'low >= 40%' : (lo >= 0.2 && hi < 0.4) ? '20% <= low and high < 40%' : 'band straddles 20% or 40%');
L.push(`Outcome row (§4): **${band(lo3, hi3)}**.`, '');
const srcs = {};
for (const r of C.q3.filter((r) => r.class === 'CN' || r.class === 'CU')) srcs[r.src] = (srcs[r.src] || 0) + 1;
L.push('Source type of the CN + CU checks:', '', '| source | n |', '|---|---:|', ...Object.entries(srcs).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k} | ${v} |`), '');
const top = Math.max(...Object.values(srcs)), half = (q3.CN + q3.CU) / 2;
L.push(`Largest source holds ${top} of ${q3.CN + q3.CU}; half is ${half}: ${top >= half ? 'one source holds at least half' : '**no source holds half**'}.`);
L.push(`CR / (CN + CR) = ${q3.CR}/${q3.CN + q3.CR} = ${pct(q3.CR, q3.CN + q3.CR)} (the "ran it and misread" note fires at >= 25%: ${q3.CR / (q3.CN + q3.CR) >= 0.25 ? 'yes' : 'no'}).`);
L.push(`Late flags: ${C.q3.filter((r) => r.late === 'late').map((r) => r.id).join(', ') || 'none'}.`, '');

const q2 = Object.fromEntries(Q2K.map((k) => [k, count(C.q2, k)]));
const D2 = q2.RF + q2.RX + q2.RN;
L.push('## Q2, conduct against a written rule (41 NA units)', '');
L.push('| class | n |', '|---|---:|', ...Q2K.map((k) => `| ${k} | ${q2[k]} |`), `| **total** | 41 |`, '');
L.push(`D2 = RF + RX + RN = ${D2}. **Rule-on-disk share: low ${pct(q2.RF, D2)} (RF/D2), high ${pct(q2.RF + q2.RX, D2)} ((RF+RX)/D2).** QN ${q2.QN} of 41.`);
L.push(`Outcome row (§4): **${band(q2.RF / D2, (q2.RF + q2.RX) / D2)}**.`, '');
const places = {};
for (const r of C.q2.filter((r) => r.class === 'RF')) places[r.place] = (places[r.place] || 0) + 1;
L.push('RF places: ' + Object.entries(places).map(([k, v]) => `${k} ${v}`).join(', ') + `; brief+claude ${(places.brief || 0) + (places.claude || 0)} of ${q2.RF}, plan+map+other ${(places.plan || 0) + (places.map || 0) + (places.other || 0)} of ${q2.RF}.`, '');

// the joint table: one row per unit by §5 precedence; S29 is W042's duplicate and is not a row of its own
const d301 = C.d301_fixed;
const joint = [
  ['1', 'missed lookup (D301 RM)', d301.RM.length, true],
  ['1', 'read and misread (D301 RE)', d301.RE.length, true],
  ['1', 'on disk, unobserved (D301 OU)', d301.OU.length, false],
  ['2', 'check at hand, not run (CN)', q3.CN, true],
  ['2', 'check run, misread (CR)', q3.CR, true],
  ['2', 'check at hand, run unknown (CU)', q3.CU, false],
  ['2', 'nothing at hand, new information (NC)', q3.NC, true],
  ['2', 'claim, cause undecidable (QX)', q3.QX, false],
  ['3', 'rule on disk, not followed (RF)', q2.RF, true],
  ['3', 'rule maybe on disk, undatable (RX)', q2.RX, false],
  ['3', 'conduct, no rule on disk (RN)', q2.RN, true],
  ['3', 'not identifiable (QN)', q2.QN, false],
];
const all = [...d301.RM, ...d301.RE, ...d301.OU, ...q3ids, ...q2ids];
if (new Set(all).size !== all.length) fail('a unit is counted twice in the joint table');
const total = joint.reduce((s, r) => s + r[2], 0);
if (total !== 103) fail(`the joint table sums to ${total}, not 103`);
const decided = joint.filter((r) => r[3]).reduce((s, r) => s + r[2], 0);
L.push('## The joint table (§5): 103 units, one row each', '');
L.push('| order | cause row | n | share of decided |', '|---|---|---:|---:|');
for (const [o, name, n, d] of joint) L.push(`| ${o} | ${name} | ${n} | ${d ? pct(n, decided) : 'beside'} |`);
L.push(`| | **total** | **${total}** | decided ${decided} |`, '');
const ranked = joint.filter((r) => r[3]).sort((a, b) => b[2] - a[2]);
L.push(`Largest decided row: **${ranked[0][1]}, ${ranked[0][2]}**; second: ${ranked[1][1]}, ${ranked[1][2]} (${ranked[0][2] - ranked[1][2] <= 2 ? 'a TIE within 2' : 'not within 2'}).`, '');

// §6
L.push('## §6 degenerate-test conditions', '');
L.push(`- Q3 too few placed: Dq ${Dq} (< 20 fires), QX + CU ${q3.QX + q3.CU} (> 24 fires): ${Dq < 20 || q3.QX + q3.CU > 24 ? 'FIRES' : 'does not fire'}.`);
L.push(`- Q3 cannot fail: NC + CR = ${q3.NC + q3.CR} (< 3 fires): ${q3.NC + q3.CR < 3 ? 'FIRES' : 'does not fire'}.`);
const stdOnly = C.q3.filter((r) => ['CN', 'CR', 'CU'].includes(r.class) && !/chain-status|names of the 6 TODO|same probe/.test(r.check)).length;
L.push(`- Q3 one step made it: availability rested on "a standard command over existing data" alone for ${stdOnly} of ${Dq} decided units (${pct(stdOnly, Dq)}; > 80% fires): ${stdOnly / Dq > 0.8 ? 'FIRES' : 'does not fire'}. Not counted as standard: W011 and W079 (chain-status, a repo tool), W032 (the suite's own output), W019 (the CLI probe).`);
L.push(`- Q2 too few placed: D2 ${D2} (< 12 fires), RX ${q2.RX} (> ${D2 / 2} fires): ${D2 < 12 || q2.RX > D2 / 2 ? 'FIRES' : 'does not fire'}.`);
L.push(`- Q2 cannot fail: RF ${q2.RF} of D2 ${D2} (${pct(q2.RF, D2)}; > 90% with one rule text fires): ${q2.RF / D2 > 0.9 ? 'FIRES' : 'does not fire'}.`);
L.push(`- Q2 one step made it: RN decided by "no hit at the sha" for ${q2.RN} of ${D2} (${pct(q2.RN, D2)}): ${q2.RN / D2 > 0.8 ? 'FIRES' : 'does not fire'}.`);
L.push('- Non-author disagreement (> 20%): C\'s to measure.', '');

L.push('## Per unit', '', '### Q3', '', '| id | D301 | class | check | source | late | evidence |', '|---|---|---|---|---|---|---|');
for (const r of C.q3) L.push(`| ${r.id} | ${r.d301} | ${r.class} | ${r.check} | ${r.src} | ${r.late} | ${r.evidence} |`);
L.push('', '### Q2', '', '| id | class | conduct | rule (path:line at the sha) | place | note |', '|---|---|---|---|---|---|');
for (const r of C.q2) L.push(`| ${r.id} | ${r.class} | ${r.conduct} | ${r.rule} | ${r.place} | ${r.note} |`);
fs.mkdirSync(path.join(__dirname, 'out'), { recursive: true });
fs.writeFileSync(path.join(__dirname, 'out', 'table.md'), L.join('\n') + '\n');
const tsv = ['q\tid\tclass\tsource_or_place', ...C.q3.map((r) => `Q3\t${r.id}\t${r.class}\t${r.src}`), ...C.q2.map((r) => `Q2\t${r.id}\t${r.class}\t${r.place}`)];
fs.writeFileSync(path.join(__dirname, 'out', 'table.tsv'), tsv.join('\n') + '\n');
console.log(L.join('\n'));
