def far_house(cv, c, s, lit=1.0, col=AMBER, k=1.0):
    """A house seen from far off: c is the middle of its base; about 0.20 * s wide."""
    if k <= 0.001:
        return
    w, h = 0.10 * s, 0.075 * s
    cv.fill(cv.box((c[0], c[1] + h / 2), w, h / 2), (0.15, 0.14, 0.25), k)
    cv.fill(cv.poly([(c[0] - w * 1.15, c[1] + h), (c[0] + w * 1.15, c[1] + h), (c[0], c[1] + h * 1.9)]), (0.11, 0.10, 0.20), k)
    if lit > 0:
        wins = [(c[0] - w * 0.5, c[1] + h * 0.55), (c[0] + w * 0.1, c[1] + h * 0.55), (c[0] + w * 0.6, c[1] + h * 0.55)]
        for i, p in enumerate(wins):
            cv.fill(cv.box(p, w * 0.16, h * 0.20), mix((1.0, 0.86, 0.55), col, 0.35 if i == 1 else 0.0), lit * k)
        cv.glow(cv.box((c[0], c[1] + h * 0.55), w * 0.8, h * 0.2), mix((1.0, 0.8, 0.5), col, 0.4), 0.05 * s, 0.35 * lit * k)


def the_land(cv, t, lit=None, k=1.0, dawn=0.0):
    """The night land and its thirty houses. Paint the sky first. lit: list of 30 values 0..1, or None for all dark.
    Our house is LAND[0]. LAND_KIND[i] and LAND_COL[i] say what kind of mind lives in house i and its colour."""
    lit = lit or [0.0] * 30
    ground = cv.Y - (HORIZON + 0.015 * torch.sin(cv.X * 2.3) + 0.008 * torch.sin(cv.X * 7.1 + 1.0))
    near = cv.sst(HORIZON, -1.0, cv.Y)[..., None]
    col = (cv.col(mix((0.07, 0.08, 0.16), (0.37, 0.31, 0.20), dawn)) * (1 - near) +
           cv.col(mix((0.04, 0.05, 0.10), (0.19, 0.15, 0.09), dawn)) * near)
    m = (cv.cov(ground) * k)[..., None]
    cv.img = cv.img * (1 - m) + col * m
    cv.light = cv.light * (1 - m)
    for i in LAND_ORDER:
        x, y, s = LAND[i]
        far_house(cv, (x, y), s * 1.6, lit=lit[i], col=LAND_COL[i], k=k)


