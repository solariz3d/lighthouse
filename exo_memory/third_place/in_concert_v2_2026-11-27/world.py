        tint = {"lib": VIOLET, "chair": TEAL, "mine": AMBER, "shop": (1.0, 0.86, 0.70), "hall": KEEPER, "kept": KEEPER}[name]
        warm = mix(PAPER, tint, 0.22)
        if name == "kept":
            warm = mix(dark, warm, 0.30 + 0.25 * kept)
        b = cv.box(((x0 + x1) / 2, (y0 + y1) / 2), (x1 - x0) / 2, (y1 - y0) / 2)
        cv.fill(b, mix(dark, warm, lv if name != "kept" else 1.0), k)
        cv.fill(cv.box(((x0 + x1) / 2, y0 + 0.012), (x1 - x0) / 2, 0.012), (0.40, 0.27, 0.17), k)        # floor
