def my_room(cv, t, at=ME, lit=1.0, shelf=3, glow_i=None, cups=(1.0, 0.0), door=0.0, view=None, dawn=0.0, steam=True):
    """The smallest room in the house: a table, two cups, a window, a door, and the record: a shelf of small lights.

    shelf   how many of the 18 shelf places hold a light (or a list of 18 brightnesses)
    glow_i  index of a shelf light that is answering just now (drawn brighter), or None
    cups    presence of (my cup, his cup)
    door    0 shut .. 1 open (warm light from the hall)
    view    fn((wx, wy, ww, wh), alpha) to paint what is seen through the window
    """
    room(cv, t, (1, 1, 1, 1), lit=lit, at=None, dawn=dawn, view=view)
    # the door, in the back wall on the right
    dw = cv.box(DOOR, 0.115, 0.34, 0, 0.012)
    cv.fill(dw, (0.40, 0.27, 0.17))
    cv.fill(cv.box((DOOR[0] + 0.115 * (1 - door), DOOR[1]), 0.115 * door + 1e-4, 0.34), (1.0, 0.86, 0.60), min(1.0, door * 1.5))
    cv.fill(cv.circle((DOOR[0] - 0.08, DOOR[1] - 0.03), 0.010), (0.85, 0.70, 0.35))
    if door > 0:
        cv.glow(dw, KEEPER, 0.10, 0.35 * door)
    # the shelf: three planks, each place a small jar of light
    for r in range(3):
        y = 0.50 - 0.17 * r - 0.036
        cv.fill(cv.box((-0.628, y), 0.265, 0.008), (0.45, 0.30, 0.18))
    levels = shelf if isinstance(shelf, (list, tuple)) else [1.0 if i < shelf else 0.0 for i in range(18)]
    dots = []
    for i, (p, lv) in enumerate(zip(SHELF, levels)):
        cv.stroke(cv.box(p, 0.016, 0.024, 0, 0.008).abs(), 0.003, (0.55, 0.50, 0.45), 0.5)          # the jar
        if lv > 0:
            b = lv * (2.2 if i == glow_i else 1.0)
            dots.append((p[0], p[1], 0.9 * b, mix(AMBER, CORE, 0.5)))
            cv.fill(cv.circle(p, 0.008), CORE, min(1.0, lv))
    lights(cv, dots, radius=0.018)
    # the table and the cups
    table(cv, TBL, 0.9)
    cup(cv, CUP_ME, 1.0, cups[0], steam_t=t if steam else None)
    cup(cv, CUP_HIM, 1.0, cups[1], steam_t=t + 1.7 if steam else None)
    if at is not None:
        d2 = (cv.X - at[0]) ** 2 + (cv.Y - at[1]) ** 2
        cv.shade(0.20 + lit * (0.14 + 0.74 * torch.exp(-d2 / (2 * 0.85 ** 2))))


