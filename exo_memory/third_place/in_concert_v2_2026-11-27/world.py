def cam_path(t, keys):
    """keys: (time, x, y, zoom); eases to a stop at each key. For a camera that keeps moving, use glide() or herm()."""
    for (t0, x0, y0, z0), (t1, x1, y1, z1) in zip(keys[:-1], keys[1:]):
        if t0 <= t <= t1:
            u = ss(t0, t1, t)
            return lerp(x0, x1, u), lerp(y0, y1, u), math.exp(lerp(math.log(z0), math.log(z1), u))
    kk = keys[0] if t < keys[0][0] else keys[-1]
    return kk[1], kk[2], kk[3]


def dawn_sky(cv, t, k, hz=HORIZON):
    """Dawn over the flat place: pink at the land, blue above, cirrus fanning from one point, a small hard moon."""
    if k <= 0:
        return
    stops = [(hz, (0.90, 0.54, 0.49)), (hz + 0.22, (0.94, 0.68, 0.56)), (hz + 0.50, (0.84, 0.74, 0.70)), (hz + 0.85, (0.56, 0.66, 0.80)),
             (hz + 1.60, (0.36, 0.50, 0.70))]
    sky = torch.zeros_like(cv.img) + cv.col(stops[-1][1])
    for (y0, c0), (y1, c1) in zip(stops[:-1], stops[1:]):
        u = ((cv.Y - y0) / (y1 - y0)).clamp(0.0, 1.0)[..., None]
        sky = torch.where(((cv.Y >= y0) & (cv.Y <= y1))[..., None], cv.col(c0) + (cv.col(c1) - cv.col(c0)) * u, sky)
    sky = torch.where((cv.Y < hz)[..., None], cv.col(stops[0][1]), sky)
    cv.img = cv.img * (1 - k) + sky * k
    cv.light = cv.light * (1 - k)
    dx, dy = cv.X - 0.02, cv.Y - hz
    r = torch.sqrt(dx * dx + dy * dy) + 1e-4
    ang = torch.atan2(dy, dx)
    lr = torch.log(r)
    a2 = ang + 0.22 * torch.sin(2.3 * lr + 1.1 * ang + 0.5) + 0.08 * torch.sin(5.1 * lr - 2.0 * ang)
    s1 = 0.5 + 0.5 * torch.sin(a2 * 11 + 2.0 * torch.sin(a2 * 3.1 + 0.8) + 0.02 * t)
    s2 = 0.5 + 0.5 * torch.sin(a2 * 27 + 1.3 * torch.sin(a2 * 5.3 + 2.1) + 1.2 * lr)
    p1 = cv.sst(0.35, 0.75, 0.5 + 0.5 * torch.sin(a2 * 2.3 + 1.7 + 2.6 * lr) * torch.sin(a2 * 5.9 - 1.9 * lr + 0.4))
    p2 = cv.sst(0.30, 0.80, 0.5 + 0.5 * torch.sin(a2 * 3.7 - 0.6 + 3.3 * lr + 0.01 * t) * torch.cos(a2 * 1.9 + 1.4 * lr))
    dens = s1 ** 2 * 0.75 * p1 + s2 ** 3 * 0.5 * p2
    env = cv.sst(0.12, 0.6, r) * (1.0 - cv.sst(1.1, 2.1, r)) * cv.sst(hz, hz + 0.25, cv.Y)
    cloud = (dens * env * (0.62 + 0.38 * torch.sin(ang * 1.1 + 0.7))).clamp(0, 1)[..., None] * (0.55 * ss(0.4, 1.0, k))
    hi = cv.sst(hz + 0.3, hz + 1.1, cv.Y)[..., None]
    cv.img = cv.img * (1 - cloud) + (cv.col((1.0, 0.80, 0.68)) * (1 - hi) + cv.col((0.98, 0.95, 0.92)) * hi) * cloud
    cv.fill(cv.circle((0.0097, hz + 0.72), 0.020), (0.99, 0.97, 0.92), ss(0.6, 1.0, k))        # seven pixels right of centre


def photo_card(cv, c, s, rot=0.0, k=1.0):
    """The photograph he brought: a flat place at sunrise, the moon over a fan of cloud. A card about 0.24 * s wide."""
    if k <= 0.001:
        return
    hw, hh = 0.12 * s, 0.075 * s
    cv.fill(cv.box((c[0] + 0.006 * s, c[1] - 0.008 * s), hw, hh, rot, 0.006 * s), (0, 0, 0), 0.22 * k)
    cv.fill(cv.box(c, hw, hh, rot, 0.006 * s), PAPER, k)
    x, y = cv.local(c, rot)
    inside = cv.box(c, hw * 0.90, hh * 0.86, rot)
    g = ((y / (hh * 0.86)) * 0.5 + 0.5).clamp(0, 1)[..., None]
    sky = cv.col((0.92, 0.56, 0.50)) * (1 - g) + cv.col((0.42, 0.56, 0.76)) * g
    land = (y < -hh * 0.48)[..., None]
    pic = torch.where(land, cv.col((0.34, 0.28, 0.18)).expand_as(sky), sky)
    m = (cv.cov(inside) * k)[..., None]
    cv.img = cv.img * (1 - m) + pic * m
    cs, sn = math.cos(rot), math.sin(rot)
    cv.fill(cv.circle((c[0] - sn * hh * 0.42, c[1] + cs * hh * 0.42), 0.0075 * s), (1.0, 0.99, 0.94), k)       # the moon
    cv.stroke(cv.box(c, hw, hh, rot, 0.006 * s).abs(), 0.0035 * s, (0.45, 0.38, 0.32), 0.7 * k)
