# janitor-task.ps1 - register the daily janitor (D287 part 2) as a Windows scheduled task, or remove it.
#
#   powershell -ExecutionPolicy Bypass -File consonance\tools\janitor-task.ps1              register (daily at 05:40)
#   powershell -ExecutionPolicy Bypass -File consonance\tools\janitor-task.ps1 -At 06:10    register at another time
#   powershell -ExecutionPolicy Bypass -File consonance\tools\janitor-task.ps1 -Check       is it registered, and its last result
#   powershell -ExecutionPolicy Bypass -File consonance\tools\janitor-task.ps1 -Uninstall   remove it (the one-line removal)
#
# WHAT IT RUNS: node consonance\tools\janitor.js --apply, which appends one line per run to <data>\janitor.jsonl, and one more per worktree
# it removes (with its HEAD and branch, so `git worktree add` undoes it; D319).
# INSTALLED BY THE CHAIR AFTER LANDING, once the librarian has seen a dry run (exo_memory/loop/plan_clean_up_after_ourselves_2026-10-10.md).
#
# THE LESSONS CARRIED FROM dev\vantage\install_vantage.ps1 AND dev\headwatch\install_headwatch.ps1, not re-derived (read those):
#   * PRE-FLIGHT - never register a task around a runner that cannot load: `node --check` first, and a dry run printed at the end.
#   * THE WSCRIPT SHIM - powershell -WindowStyle Hidden still flashes a console and can steal focus; wscript.exe never makes one.
#   * WAIT FOR THE EXIT CODE - the shim waits, so the scheduler records the janitor's own result, not the shim's.
# Daily, StartWhenAvailable (a missed run happens at the next wake), 60-minute limit (a first run over ~90,000 temp folders takes
# minutes; a hung one should die), IgnoreNew, NO WakeToRun (nothing here should wake a sleeping machine). 05:40 is after the dream
# cycle's 04:30 window and before the keeper's day.
#
# ASCII ONLY in this file: PowerShell 5.1 reads a .ps1 without a BOM as ANSI, and a UTF-8 dash breaks the parse.
param(
  [string]$At = "05:40",
  [string]$LauncherDir = (Join-Path $env:LOCALAPPDATA "Consonance"),
  [switch]$Uninstall,
  [switch]$Check
)
$ErrorActionPreference = "Stop"
$TaskName = "Consonance Janitor"

if ($Uninstall) {
  try {
    Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false -ErrorAction Stop
    Write-Host "Unregistered '$TaskName'." -ForegroundColor Green
  } catch {
    Write-Host "No task named '$TaskName' to remove." -ForegroundColor Yellow
  }
  exit 0
}

if ($Check) {
  $t = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
  if (-not $t) { Write-Host "NOT REGISTERED: $TaskName" -ForegroundColor Yellow; exit 1 }
  $i = Get-ScheduledTaskInfo -TaskName $TaskName
  Write-Host "Task:     $TaskName  [$($t.State)]"
  Write-Host "Runs:     $($t.Actions[0].Execute) $($t.Actions[0].Arguments)"
  Write-Host "LastRun:  $($i.LastRunTime)   result $($i.LastTaskResult)"
  Write-Host "NextRun:  $($i.NextRunTime)"
  exit 0
}

# -- Locate the runner and node --------------------------------------------
$repo   = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
$runner = Join-Path $repo "consonance\tools\janitor.js"
if (-not (Test-Path $runner)) { throw "janitor.js not found at $runner" }
$node = (Get-Command node -ErrorAction SilentlyContinue).Source
if (-not $node) { throw "node not found on PATH; the task would register around a command that cannot run" }

# -- PRE-FLIGHT: refuse to register around a runner that will not load -------
& $node --check $runner 2>&1 | Out-Null
if ($LASTEXITCODE -ne 0) {
  Write-Host "REFUSING TO INSTALL: janitor.js does not parse." -ForegroundColor Red
  & $node --check $runner
  throw "runner failed pre-flight; task not registered"
}
Write-Host "Runner pre-flight: parses clean." -ForegroundColor Green

# -- THE CONFIG CHECK, printed loudly: the two roots that are this machine's live in ~/.consonance.json, never in the code (D287-e2) --
# A WARNING, not a refusal (the vantage installer's form): registering first is a legitimate order, but not without being told that class (b) will
# move nothing and class (d) will not run until the keys are set.
$cfgPath = Join-Path $env:USERPROFILE ".consonance.json"
$cfg = $null
if (Test-Path $cfgPath) { try { $cfg = Get-Content $cfgPath -Raw | ConvertFrom-Json } catch { $cfg = $null } }
foreach ($k in @("archive_dir", "worktrees_dir")) {
  if (-not $cfg -or -not $cfg.$k) {
    Write-Host "WARNING - $k is NOT set in $cfgPath; the janitor skips its class until it is (see the janitor's NOTE lines)." -ForegroundColor Yellow
  } else {
    Write-Host "Config:   $k = $($cfg.$k)" -ForegroundColor Green
  }
}

# -- The launcher shim ---------------------------------------------------------
if (-not (Test-Path $LauncherDir)) { New-Item -ItemType Directory -Path $LauncherDir -Force | Out-Null }
$vbs       = Join-Path $LauncherDir "janitor_launch.vbs"
$launchLog = Join-Path $LauncherDir "janitor_launch.log"
$vbsBody = @"
' janitor_launch.vbs - GENERATED by janitor-task.ps1. Do not hand-edit: re-run the installer instead.
' ASCII ONLY in this file: wscript refuses a UTF-8 BOM and misreads non-ASCII.
Option Explicit
Dim shell, fso, rc, cmd
Set shell = CreateObject("WScript.Shell")
Set fso = CreateObject("Scripting.FileSystemObject")
cmd = """$node"" ""$runner"" --apply"
Stamp "launch"
' 0 = no window ever. True = WAIT, so the exit code below is the janitor's own.
rc = shell.Run(cmd, 0, True)
Stamp "exit " & rc
WScript.Quit rc

Sub Stamp(msg)
  On Error Resume Next
  Dim f
  Set f = fso.OpenTextFile("$launchLog", 8, True)
  f.WriteLine Now & "  " & msg
  f.Close
End Sub
"@
[System.IO.File]::WriteAllText($vbs, $vbsBody, [System.Text.UTF8Encoding]::new($false))

# -- The scheduled task --------------------------------------------------------
$action  = New-ScheduledTaskAction -Execute "wscript.exe" -Argument "//B //Nologo `"$vbs`""
$trigger = New-ScheduledTaskTrigger -Daily -At $At
$taskSettings = New-ScheduledTaskSettingsSet -StartWhenAvailable -ExecutionTimeLimit (New-TimeSpan -Minutes 60) -MultipleInstances IgnoreNew
Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger -Settings $taskSettings `
  -Description "janitor.js --apply (D287): removes the room's old temp test folders, idle cargo targets in scratchpads and merged worktrees, removes landed, clean, idle worktrees in the owned folders (worktrees_dirs in ~/.consonance.json; never --force) and reports the stray worktrees outside them, and moves old task-output logs to the archive_dir set in ~/.consonance.json. One line per run in <data>\janitor.jsonl, and one per removed worktree. Remove: powershell -ExecutionPolicy Bypass -File consonance\tools\janitor-task.ps1 -Uninstall" `
  -Force | Out-Null

Write-Host "Registered '$TaskName': daily at $At (machine must already be awake; WakeToRun is off)." -ForegroundColor Green
Write-Host "Launcher:   $vbs"
Write-Host "Launch log: $launchLog  (a 'launch' with no matching 'exit 0' means the janitor failed or died)"
Write-Host "Remove:     powershell -ExecutionPolicy Bypass -File `"$PSCommandPath`" -Uninstall"
Write-Host ""
Write-Host "What it would do RIGHT NOW (dry run, changes nothing):"
& $node $runner
